import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { buildMarginCallNotification, buildWarningNotification } from '../src/lib/notifier';
import { initializeBatchFinance, syncBatchFinance, type BatchLike } from '../src/lib/riskEngine';
import { notificationMessage } from '../src/lib/server/notificationContext';
import { notificationEmailHtml, notificationHighlights } from '../src/lib/notificationFormatting';
import { formatTelegramAlert } from '../src/lib/server/telegram';
const b = { id:'test', batchNumber:'Oceanova01-2026-Win003', stockSymbol:'XMAX', stockPriceAtStart:10, currentStockPrice:7, initialTotalAmount:1000000, priorityAmount:700000, subordinateAmount:300000, totalShares:100000, cumulativeMarginCalls:0, signDate:new Date('2026-01-01'), clients:[{id:'a',name:'A',investmentAmount:700000,status:'ACTIVE',sharesHeld:70000,avgCostPrice:10,profitSplitClient:40,profitSplitInstitution:60,signDate:new Date('2026-01-01')}], marginCalls:[] } as unknown as BatchLike;
initializeBatchFinance(b); syncBatchFinance(b);
const round = b.finance!.rounds.at(-1)!;
assert.equal(round.triggerStockPrice,7); assert.equal(round.triggerClientCount,1);
b.currentStockPrice=8; syncBatchFinance(b);
assert.equal(b.finance!.rounds.at(-1)!.triggerStockPrice,7);
const call = b.marginCalls![0]; call.fulfilledAmount=50000;
const p = buildMarginCallNotification(b as any,call as any);
assert.match(p.message,/触发时价格：\$7.00/); assert.match(p.message,/股数参考价：\$8.00/);
assert.match(p.message,/批次客户：1 人/); assert.match(p.message,/需补仓金额：\$250,000.00/); assert.match(p.message,/对应股数：31,250 股/);
const msg=notificationMessage({...p,details:{...p.details,deliveryContext:{kind:'manual',channel:'email',actorId:'a',actorName:'管理员 <script>',actorEmail:'a@recipient.test'}}});
const html=notificationEmailHtml(p.title,msg);
assert.ok(html.includes('&lt;script&gt;')); assert.ok(!html.includes('<script>'));
assert.ok(html.includes('<strong>需补仓金额：$250,000.00</strong>'));
assert.ok(html.includes('<strong>对应股数：31,250 股</strong>'));
const tg=formatTelegramAlert(p.title,msg,p.severity);
for(const entity of tg.entities) assert.ok(entity.offset>=0&&entity.offset+entity.length<=tg.text.length);
for(const label of ['触发时价格','需补仓金额','对应股数','批次客户']) assert.ok(tg.entities.some(e=>tg.text.slice(e.offset,e.offset+e.length).startsWith(label)));
assert.ok(notificationHighlights(msg).every((r,i,all)=>i===0||all[i-1].offset+all[i-1].length<=r.offset));
const legacy=buildMarginCallNotification({...b,finance:undefined} as any,{...call,triggerStockPrice:undefined} as any);
assert.match(legacy.message,/触发时价格：未留存/);
const warning=buildWarningNotification({...b,currentStockPrice:9} as any,10,10);
assert.match(warning.message,/需补仓金额：\$0.00/); assert.match(warning.message,/对应股数：0 股/);
writeFileSync('/tmp/riskcontrol-alert-preview.html',html);
console.log('PASS trigger snapshot, current reference price, client counts, remaining amount/share conversion, warning zero, legacy honesty, HTML escaping and Telegram UTF-16 bold ranges');
