import assert from 'node:assert/strict';
import { initializeBatchFinance, executeInstitutionTopup, settleClientPosition, type BatchLike } from '../src/lib/riskEngine';
import { replayBatchDay } from '../src/lib/batchHistoryReplay';
const batch = { id: 'test', stockSymbol: 'TEST', signDate: '2026-01-01', maturityDate: '2028-01-01', initialTotalAmount: 1000, priorityAmount: 700, subordinateAmount: 300, stockPriceAtStart: 100, currentStockPrice: 70, totalShares: 10, cumulativeMarginCalls: 0, clients: [{id:'a',batchId:'test',name:'A',bdManager:'BD',signDate:'2026-01-01',investmentAmount:700}], marginCalls: [] } as unknown as BatchLike;
initializeBatchFinance(batch);
executeInstitutionTopup(batch, { amount: 100, collateralType: 'stock' });
batch.finance!.trades.forEach(t => { t.createdAt = '2026-02-02T16:00:00Z'; });
const before = replayBatchDay(batch, '2026-01-05', 90)!;
assert.ok(Math.abs(before.marketValue - 900) < .01); assert.equal(before.cumulativeTopup, 0);
const after = replayBatchDay(batch, '2026-02-02', 70)!;
assert.equal(after.topupAmount, 100); assert.equal(after.topups[0].type, 'stock');
assert.ok(Math.abs(after.marketValue - 800) < .01);
assert.equal(replayBatchDay(batch, '2025-12-30', 80), null);
batch.currentStockPrice = 120;
const snapshot = settleClientPosition(batch, 'a', { force: true, confirmLockedExit: true });
snapshot.settledAt = '2026-03-03T16:00:00Z';
const old = replayBatchDay(batch, '2026-02-02', 70)!;
assert.equal(old.activeClients, 1); assert.equal(old.marketValue, after.marketValue);
const ended = replayBatchDay(batch, '2026-03-04', 150)!;
assert.equal(ended.activeClients, 0); assert.ok(Math.abs(ended.marketValue) < .01);
assert.equal(replayBatchDay(batch, '2026-03-04', 200)!.totalPnL, ended.totalPnL);
assert.equal(batch.finance!.settlements.a.stockPrice, 120);
console.log('PASS: daily close replay excludes future topups, restores pre-exit holdings, freezes realized returns and leaves source ledger untouched');
